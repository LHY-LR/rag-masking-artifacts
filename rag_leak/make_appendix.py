# ---------------- A.2 HotpotQA 四臂 ----------------
A(r"\subsection{HotpotQA: four arms and the gate}")
# gate drop 是**聚合差**，聚合为 0 不一定代表"什么都没变"：逐题不一致但两个方向恰好抵消时也会是 0。
# 实测 Qwen3-0.6B 与 Qwen3-4B 就是这种相抵（各题集方向数完全相等）⇒ 表注必须写明，
# 否则读者会把 0.0% 读成"替换没有改变任何题"，那是错的。
_dis = {}
for name, d, nf in HOTPOT:
    _p = R / d / (nf + "oracle_rows.jsonl")
    if _p.is_file():
        _rows = [json.loads(x) for x in _p.read_text(encoding="utf-8").splitlines() if x.strip()]
        _up = sum(1 for r in _rows if r["em_sub"] == 1 and r["em_orig"] == 0)
        _dn = sum(1 for r in _rows if r["em_orig"] == 1 and r["em_sub"] == 0)
        _dis[name] = (_up + _dn, len(_rows), _up == _dn)
_cancel = ", ".join("%s (%d/%d items)" % (n, c[0], c[1]) for n, c in _dis.items() if c[0])
_bal = " and ".join(n for n, c in _dis.items() if c[0] and c[2])
A(r"\begin{center}\small")
A(r"\captionof{table}{HotpotQA C-line, final construction (v2), $n{=}393$, context budget 4096. "
  r"The last column is the oracle-answerability gate of \S\ref{sec:gate3}: the drop in "
  r"accuracy between the original and substituted gold evidence. The frozen thresholds are "
  r"$\leq 3\%$ GO, $\leq 8\%$ REVISE, $>8\%$ ABANDON. The drop is an \emph{aggregate} "
  r"difference, so a value of $0.0\%$ can arise from cancellation rather than from the "
  r"substitution changing nothing: the two arms disagree item by item on " + _cancel +
  r"; for " + _bal + r" these disagreements are exactly balanced, which is what makes the "
  r"aggregate drop zero there.}")
