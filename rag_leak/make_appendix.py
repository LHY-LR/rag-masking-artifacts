# B 线逐格 masking 的 95% CI：读 analyze_kaxis 产物，masking CI = 反射后的 DiD CI
ANALYSIS = {"Qwen3-0.6B": "q3_06b", "Qwen3-1.7B": "q3_17b", "Qwen3-4B": "q3_4b",
            "Qwen3-4B-Instruct": "q3_4bi", "Qwen3-8B": "q3_8b",
            "Qwen3.5-4B-Base": "q35_4b"}


def masking_ci(model, k):
    with open(R / ("out_b8_fix_analysis_%s.json" % ANALYSIS[model]), encoding="utf-8") as f:
        j = json.load(f)
    lo, hi = j["per_k"]["k=%d" % k]["all"]["did_ci"]
    return -hi, -lo


