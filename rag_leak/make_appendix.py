# ---------------- 后处理：让长表无法跨页断开 ----------------
# 为什么需要：附录里的表是 `center` + 裸 `tabular`（不是 float、也不是 longtable），
# 而 LaTeX 的裸 tabular **可以**在分页处断开且**不会重复表头** —— 最长的审计表有 22 行，
# 一旦落在页边界，读者会看到"半张表 + 无表头"。这里把行数 ≥ MIN_ROWS 的表整体裹进
# `minipage`（不可分割），行数少的表保持原样以免影响排版。
MIN_ROWS = 12
_out: list[str] = []
_i = 0
_wrapped = 0
while _i < len(L):
    line = L[_i]
    if line == r"\begin{center}\small":
        # 找配对的 \end{center}
        _j = _i + 1
        while _j < len(L) and L[_j] != r"\end{center}":
            _j += 1
        block = L[_i + 1:_j]
        rows = sum(1 for b in block if b.endswith(r"\\"))
        if rows >= MIN_ROWS and any(b.startswith(r"\begin{tabular}") for b in block):
            _out.append(line)
            _out.append(r"\begin{minipage}{\linewidth}")
            _out.extend(block)
            _out.append(r"\end{minipage}")
            _out.append(L[_j])
            _wrapped += 1
            _i = _j + 1
            continue
    _out.append(line)
    _i += 1
L = _out
print("[后处理] %d 张 ≥%d 行的表已裹入 minipage（防跨页丢表头）" % (_wrapped, MIN_ROWS))

OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
print("已写 %s（%d 行，%.1f KB）" % (OUT, len(L), OUT.stat().st_size / 1024))
